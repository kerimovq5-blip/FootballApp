import UIKit

extension UIColor {
    // MARK: - Main
    //----------------------------------------
    @nonobjc class var background: UIColor {
        return UIColor(named: "Background")!
    }

    @nonobjc class var backgroundColor2: UIColor {
        return UIColor(named: "backgroundColor2")!
    }

    // MARK: - Text
    //----------------------------------------
    @nonobjc class var textPrimary: UIColor {
        return UIColor(named: "TextPrimary")!
    }

    @nonobjc class var textSecondary: UIColor {
        return UIColor(named: "TextSecondary")!
    }

    @nonobjc class var titleColor: UIColor {
        return UIColor(named: "ButtonTitleColor")!
    }

    @nonobjc class var labelColor: UIColor {
        return UIColor(named: "LabelColor")!
    }

    @nonobjc class var placeholderColor: UIColor {
        return UIColor(named: "placeholdercolor")!
    }

    // MARK: - Button / Accent
    //----------------------------------------
    @nonobjc class var accent: UIColor {
        return UIColor(named: "AccentColor")!
    }

    @nonobjc class var buttonTitlecolor: UIColor {
        return UIColor(named: "ButtonTitleColor")!
    }

}
